-- EXPERIENCE FINDER — SKEMA DATABASE + MIGRASI AMAN
-- Aman dijalankan pada proyek baru maupun database versi lama yang memakai public.stories.author_id.
-- Data stories/comments lama tidak dihapus. Pemilik cerita lama dipindahkan ke schema private
-- sebelum kolom author_id lama dihapus dari tabel yang dapat dibaca pengguna.
-- Jalankan seluruh file ini sekali di Supabase Dashboard > SQL Editor > New query.
-- Jangan pernah menaruh Supabase secret/service_role key di aplikasi browser.

begin;

-- 1. Tabel cerita. Struktur ini juga menjadi target akhir untuk database lama.
create table if not exists public.stories (
  id bigint generated by default as identity primary key,
  story_key text not null unique,
  author_name text not null default 'Pengguna',
  category text not null,
  situation text not null,
  title text not null,
  happened text not null,
  did text not null,
  unexpected text not null default '',
  lesson text not null,
  repeat text not null default '',
  is_anonymous boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.stories add column if not exists author_name text not null default 'Pengguna';
alter table public.stories add column if not exists category text;
alter table public.stories add column if not exists situation text;
alter table public.stories add column if not exists title text;
alter table public.stories add column if not exists happened text;
alter table public.stories add column if not exists did text;
alter table public.stories add column if not exists unexpected text not null default '';
alter table public.stories add column if not exists lesson text;
alter table public.stories add column if not exists repeat text not null default '';
alter table public.stories add column if not exists is_anonymous boolean not null default false;
alter table public.stories add column if not exists created_at timestamptz not null default now();
alter table public.stories add column if not exists updated_at timestamptz not null default now();

create unique index if not exists stories_story_key_uidx on public.stories (story_key);
create index if not exists stories_created_at_idx on public.stories (created_at desc);

-- 2. Simpan hubungan story_key -> user_id di schema privat (bukan tabel API publik).
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table if not exists private.story_owners (
  story_key text primary key references public.stories(story_key) on delete cascade,
  owner_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table private.story_owners enable row level security;
revoke all on table private.story_owners from public, anon, authenticated;

-- 3. Migrasikan pemilik dari skema lama. ON CONFLICT DO NOTHING menjaga mapping
--    yang sudah pernah dimigrasikan agar tidak tertimpa saat file dijalankan ulang.
do $migration$
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'stories'
      and column_name = 'author_id'
  ) then
    execute $copy$
      insert into private.story_owners (story_key, owner_id)
      select story_key, author_id
      from public.stories
      where author_id is not null
      on conflict (story_key) do nothing
    $copy$;
  end if;
end
$migration$;

-- 4. Rapikan kategori lama tanpa menghapus cerita atau komentar.
update public.stories
set category = case lower(btrim(category))
  when 'interview kerja' then 'Karier'
  when 'mencari kerja' then 'Karier'
  when 'internship' then 'Karier'
  when 'freelance' then 'Karier'
  when 'adaptasi kerja' then 'Karier'
  when 'cv & portofolio' then 'Karier'
  when 'organisasi' then 'Organisasi'
  when 'presentasi' then 'Pendidikan'
  when 'tugas kuliah' then 'Pendidikan'
  when 'kuliah' then 'Pendidikan'
  when 'pertemanan' then 'Pertemanan & Sosial'
  when 'public speaking' then 'Pengembangan Diri'
  else 'Kehidupan Sehari-hari'
end
where category is null or category not in (
  'Karier','Pendidikan','Organisasi','Pertemanan & Sosial',
  'Pengembangan Diri','Kehidupan Sehari-hari'
);

update public.stories set author_name = 'Anonim' where is_anonymous = true;

-- 5. Hapus semua policy cerita lama sebelum menghapus kolom author_id.
--    Ini menghindari policy lama yang masih merujuk ke kolom pemilik.
do $policies$
declare policy_row record;
begin
  for policy_row in
    select policyname from pg_policies
    where schemaname = 'public' and tablename = 'stories'
  loop
    execute format('drop policy if exists %I on public.stories', policy_row.policyname);
  end loop;
end
$policies$;

-- author_id lama sudah dipindahkan ke private.story_owners di langkah 3.
-- Kolom ini sengaja dihapus agar tidak bisa dibaca melalui Data API.
alter table public.stories drop column if exists author_id;

-- 6. Komentar tetap tersimpan. Tabel ini juga sudah ada pada versi terdahulu.
create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  story_key text not null,
  author_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null default 'Pengguna',
  body text not null check (char_length(body) between 1 and 1200),
  created_at timestamptz not null default now()
);
create index if not exists comments_story_created_idx on public.comments (story_key, created_at asc);

-- 7. Atur hak akses tabel secara eksplisit. RLS dan GRANT harus sama-sama benar.
grant usage on schema public to authenticated;
alter table public.stories enable row level security;
alter table public.comments enable row level security;

revoke all on table public.stories from public, anon, authenticated;
grant select on table public.stories to authenticated;

revoke all on table public.comments from public, anon, authenticated;
grant select, insert, delete on table public.comments to authenticated;

do $sequence_grant$
declare sequence_name text;
begin
  sequence_name := pg_get_serial_sequence('public.comments', 'id');
  if sequence_name is not null then
    execute format('grant usage, select on sequence %s to authenticated', sequence_name::regclass);
  end if;
end
$sequence_grant$;

-- Hapus policy komentar lama, kemudian pasang policy minimal.
do $comment_policies$
declare policy_row record;
begin
  for policy_row in
    select policyname from pg_policies
    where schemaname = 'public' and tablename = 'comments'
  loop
    execute format('drop policy if exists %I on public.comments', policy_row.policyname);
  end loop;
end
$comment_policies$;

create policy "Authenticated users can read comments"
  on public.comments for select to authenticated
  using ((select auth.uid()) is not null);

create policy "Users can post comments as themselves"
  on public.comments for insert to authenticated
  with check ((select auth.uid()) = author_id);

create policy "Users can delete their own comments"
  on public.comments for delete to authenticated
  using ((select auth.uid()) = author_id);

-- Cerita hanya dapat dibaca setelah login.
create policy "Authenticated users can read stories"
  on public.stories for select to authenticated
  using ((select auth.uid()) is not null);

-- Tidak ada GRANT INSERT/UPDATE/DELETE langsung pada stories.
-- Operasi tulis dilakukan melalui RPC di bawah yang memeriksa pemilik di schema private.

-- 8. Ambil daftar ID cerita milik akun aktif tanpa membuka tabel pemilik.
create or replace function public.get_my_story_keys()
returns setof text
language sql
stable
security definer
set search_path = ''
as $$
  select owner_row.story_key
  from private.story_owners as owner_row
  where owner_row.owner_id = (select auth.uid());
$$;

-- 9. Buat cerita dan catat pemilik secara atomik di database.
create or replace function public.create_story(
  p_story_key text,
  p_author_name text,
  p_category text,
  p_situation text,
  p_title text,
  p_happened text,
  p_did text,
  p_unexpected text,
  p_lesson text,
  p_repeat text,
  p_is_anonymous boolean
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := (select auth.uid());
  anonymous_choice boolean := coalesce(p_is_anonymous, false);
begin
  if current_user_id is null then
    raise exception 'Login diperlukan untuk mengirim cerita.' using errcode = '28000';
  end if;
  if p_story_key is null or char_length(btrim(p_story_key)) not between 1 and 80 then
    raise exception 'ID cerita tidak valid.' using errcode = '22023';
  end if;
  if p_category not in ('Karier','Pendidikan','Organisasi','Pertemanan & Sosial','Pengembangan Diri','Kehidupan Sehari-hari') then
    raise exception 'Kategori cerita tidak valid.' using errcode = '22023';
  end if;
  if char_length(btrim(coalesce(p_title,''))) not between 1 and 100
    or char_length(btrim(coalesce(p_situation,''))) not between 1 and 80
    or char_length(btrim(coalesce(p_happened,''))) not between 1 and 900
    or char_length(btrim(coalesce(p_did,''))) not between 1 and 900
    or char_length(btrim(coalesce(p_lesson,''))) not between 1 and 700
    or char_length(coalesce(p_unexpected,'')) > 700
    or char_length(coalesce(p_repeat,'')) > 700 then
    raise exception 'Isi cerita tidak sesuai batas formulir.' using errcode = '22023';
  end if;

  insert into public.stories (
    story_key, author_name, category, situation, title,
    happened, did, unexpected, lesson, repeat, is_anonymous
  ) values (
    btrim(p_story_key),
    case when anonymous_choice then 'Anonim' else left(coalesce(nullif(btrim(p_author_name),''),'Pengguna'),40) end,
    p_category, btrim(p_situation), btrim(p_title), btrim(p_happened), btrim(p_did),
    coalesce(p_unexpected,''), btrim(p_lesson), coalesce(p_repeat,''), anonymous_choice
  );

  insert into private.story_owners (story_key, owner_id)
  values (btrim(p_story_key), current_user_id);

  return btrim(p_story_key);
end;
$$;

-- 10. Ubah cerita hanya bila pemilik pada tabel privat cocok dengan auth.uid().
create or replace function public.update_my_story(
  p_story_key text,
  p_author_name text,
  p_category text,
  p_situation text,
  p_title text,
  p_happened text,
  p_did text,
  p_unexpected text,
  p_lesson text,
  p_repeat text,
  p_is_anonymous boolean
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := (select auth.uid());
  anonymous_choice boolean := coalesce(p_is_anonymous, false);
begin
  if current_user_id is null then
    raise exception 'Login diperlukan untuk mengubah cerita.' using errcode = '28000';
  end if;
  if not exists (
    select 1 from private.story_owners as owner_row
    where owner_row.story_key = p_story_key and owner_row.owner_id = current_user_id
  ) then
    raise exception 'Kamu tidak memiliki izin untuk mengubah cerita ini.' using errcode = '42501';
  end if;
  if p_category not in ('Karier','Pendidikan','Organisasi','Pertemanan & Sosial','Pengembangan Diri','Kehidupan Sehari-hari') then
    raise exception 'Kategori cerita tidak valid.' using errcode = '22023';
  end if;
  if char_length(btrim(coalesce(p_title,''))) not between 1 and 100
    or char_length(btrim(coalesce(p_situation,''))) not between 1 and 80
    or char_length(btrim(coalesce(p_happened,''))) not between 1 and 900
    or char_length(btrim(coalesce(p_did,''))) not between 1 and 900
    or char_length(btrim(coalesce(p_lesson,''))) not between 1 and 700
    or char_length(coalesce(p_unexpected,'')) > 700
    or char_length(coalesce(p_repeat,'')) > 700 then
    raise exception 'Isi cerita tidak sesuai batas formulir.' using errcode = '22023';
  end if;

  update public.stories set
    author_name = case when anonymous_choice then 'Anonim' else left(coalesce(nullif(btrim(p_author_name),''),'Pengguna'),40) end,
    category = p_category,
    situation = btrim(p_situation),
    title = btrim(p_title),
    happened = btrim(p_happened),
    did = btrim(p_did),
    unexpected = coalesce(p_unexpected,''),
    lesson = btrim(p_lesson),
    repeat = coalesce(p_repeat,''),
    is_anonymous = anonymous_choice,
    updated_at = now()
  where story_key = p_story_key;

  return true;
end;
$$;

-- 11. Hapus cerita dan komentarnya hanya setelah kepemilikan terverifikasi.
create or replace function public.delete_my_story(p_story_key text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := (select auth.uid());
begin
  if current_user_id is null then
    raise exception 'Login diperlukan untuk menghapus cerita.' using errcode = '28000';
  end if;
  if not exists (
    select 1 from private.story_owners as owner_row
    where owner_row.story_key = p_story_key and owner_row.owner_id = current_user_id
  ) then
    raise exception 'Kamu tidak memiliki izin untuk menghapus cerita ini.' using errcode = '42501';
  end if;

  delete from public.comments where story_key = p_story_key;
  delete from public.stories where story_key = p_story_key;
  return true;
end;
$$;

-- 12. Fungsi SECURITY DEFINER hanya boleh dipanggil role authenticated.
revoke execute on function public.get_my_story_keys() from public, anon;
revoke execute on function public.create_story(text,text,text,text,text,text,text,text,text,text,boolean) from public, anon;
revoke execute on function public.update_my_story(text,text,text,text,text,text,text,text,text,text,boolean) from public, anon;
revoke execute on function public.delete_my_story(text) from public, anon;

grant execute on function public.get_my_story_keys() to authenticated;
grant execute on function public.create_story(text,text,text,text,text,text,text,text,text,text,boolean) to authenticated;
grant execute on function public.update_my_story(text,text,text,text,text,text,text,text,text,text,boolean) to authenticated;
grant execute on function public.delete_my_story(text) to authenticated;

commit;

